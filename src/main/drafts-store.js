// Crash-safe draft-journal storage primitive (PERS-01, PERS-03).
//
// This is the foundation every later Phase 6 plan (boot sequencing,
// draft-journal.js, crash-recovery e2e) builds on: a read/write/scan/sweep
// layer over `userData/drafts/`, reusing Phase 4's `atomic-write.js` for
// every write. It never touches the user's own `.md` file -- drafts live
// exclusively as `<uuid>.md` + `<uuid>.json` pairs in their own directory.
//
// Mirrors text-file.js's shape (safe-path check -> fs op -> structured
// result, never throws for the caller-facing surface) and atomic-write.js's
// own write primitive, per 06-PATTERNS.md's "src/main/drafts-store.js"
// pattern assignment.
//
// Verified gap (06-RESEARCH.md, confirmed directly against this repo's own
// atomic-write.js line 126): `fsPromises.open(tempPath, 'w')` does NOT
// create parent directories. A first-ever launch with no pre-existing
// `userData/drafts/` would throw ENOENT on the very first writeDraft() call
// unless ensureDraftsDirExists() runs first -- this module is the one place
// that gap must be closed.
//
// Startup-scan hygiene (06-RESEARCH.md Pitfall 3): atomic-write.js names its
// temp file `<basename>.<pid>.<random>.tmp` in the SAME directory as the
// target. A process killed mid-write leaves that `.tmp` file behind
// permanently -- no write is ever pending across a restart, so any `.tmp`
// found at startup is guaranteed orphaned garbage from a previous process's
// death. scanDraftsDir() must never count it as a draft, and sweeps it from
// disk as a hygiene measure.
//
// Security (T-6-01, T-6-02, T-6-03; 06-01-PLAN.md threat_model; CR-02,
// 06-REVIEW.md): draft uuids are main-process-generated by default
// (crypto.randomUUID()), but the renderer IS allowed to propose one back on
// a repeat write (so the same draft file is reused instead of duplicated)
// and MUST supply one on delete. `registerDraftsIpc`'s handlers re-validate
// any renderer-supplied uuid against a canonical UUID shape (UUID_RE, below)
// BEFORE it is ever used in a `path.join()` call, and reject outright (throw,
// never silently substitute a fresh id) anything that does not match --
// this is what actually closes the path-traversal gap a previous version of
// this comment incorrectly claimed was already closed by construction. Any
// renderer-supplied ORIGINAL file path (meta.filePath) is re-validated via
// isSafeFilePath before it is ever passed to fs.stat, exactly as
// text-file.js already does for every other renderer-supplied path. A
// corrupt/unparsable sidecar JSON is skipped and counted, never thrown --
// startup must never be blocked by a bad draft.
//
// NOTE: written as ESM import/export, not require()/module.exports -- the
// electron-vite main build's Rollup bundling only traverses relative local
// files that use static ES import syntax (Phase 1 decision).
import { ipcMain } from 'electron'
import fsPromises from 'node:fs/promises'
import path from 'node:path'
import crypto from 'node:crypto'
import { atomicWrite } from './atomic-write.js'
import { isSafeFilePath } from './path-guard.js'

const DRAFT_NAME_RE = /^([0-9a-f-]{36})\.(md|json)$/

// [CR-02, 06-REVIEW.md] Canonical UUID shape (any RFC 4122 version, not
// strictly v4 -- crypto.randomUUID() emits v4, but this regex intentionally
// does not pin the version/variant nibbles, since the only property this
// gate needs to guarantee is "cannot possibly be a path-traversal payload",
// not "was generated by this exact algorithm"). Matches 06-RESEARCH.md's own
// Security Domain-prescribed mitigation verbatim: "validate it matches a
// canonical UUID regex before use."
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i

/**
 * Ensures `draftsDir` exists, creating it (and any missing parents)
 * recursively. Required before the first-ever writeDraft() call on a fresh
 * `userData/drafts/` -- see this module's header comment for the verified
 * atomic-write.js gap this closes.
 */
async function ensureDraftsDirExists (draftsDir) {
  await fsPromises.mkdir(draftsDir, { recursive: true })
}

/**
 * Writes a draft pair to `draftsDir`: `<uuid>.md` (the document content) and
 * `<uuid>.json` (sidecar metadata), both via atomicWrite -- never a raw
 * fsPromises.writeFile. `meta` is `{ filePath: string|null, name: string }`.
 *
 * Independently stats the ORIGINAL user file (meta.filePath) to capture
 * `{ mtimeMs, size }` at journal-write time, for later conflict detection
 * (PERS-02's "flag the conflict" rule). meta.filePath is re-validated via
 * isSafeFilePath before any fs.stat call (T-6-02) -- a null filePath
 * (untitled document), an unsafe path, or a stat failure (e.g. the file has
 * been deleted) all record `originalStat: null` rather than throwing.
 *
 * Never writes into meta.filePath itself -- only into draftsDir.
 */
async function writeDraft (draftsDir, uuid, content, meta) {
  const filePath = meta && typeof meta.filePath === 'string' ? meta.filePath : null
  const name = meta && meta.name

  let originalStat = null
  if (filePath && isSafeFilePath(filePath)) {
    try {
      const stat = await fsPromises.stat(filePath)
      originalStat = { mtimeMs: stat.mtimeMs, size: stat.size }
    } catch {
      // Missing/unreadable original file at journal-write time is not a
      // draft-write failure -- the draft is still fully written, just
      // without a comparison stat. Untitled documents (filePath === null)
      // take this same originalStat: null path via the outer condition.
      originalStat = null
    }
  }

  await atomicWrite(path.join(draftsDir, `${uuid}.md`), content)
  await atomicWrite(
    path.join(draftsDir, `${uuid}.json`),
    JSON.stringify({ uuid, filePath, name, originalStat, writtenAt: Date.now() })
  )
}

/**
 * Deletes both halves of a draft pair (`<uuid>.md` and `<uuid>.json`) from
 * `draftsDir`. Idempotent -- deleting an already-deleted or never-written
 * draft is not an error; each unlink is wrapped in `.catch(() => {})`.
 */
async function deleteDraft (draftsDir, uuid) {
  await fsPromises.unlink(path.join(draftsDir, `${uuid}.md`)).catch(() => {})
  await fsPromises.unlink(path.join(draftsDir, `${uuid}.json`)).catch(() => {})
}

/**
 * Scans `draftsDir` for valid draft pairs. Any `.tmp`-suffixed entry is
 * atomic-write.js's own orphaned temp file from a previous process's death
 * (06-RESEARCH.md Pitfall 3) -- it is deleted (best-effort) and never
 * counted as a draft. Every remaining entry is matched against
 * `<uuid>.(md|json)`; a uuid needs BOTH halves present to be considered.
 * For each candidate uuid, the sidecar JSON is parsed and the body read --
 * either failure marks the uuid corrupt/partial: excluded from `valid`,
 * counted in `corruptCount`, logged via console.error, never thrown.
 *
 * Returns `{ valid: [{ uuid, filePath, name, content, originalStat }], corruptCount }`.
 */
async function scanDraftsDir (draftsDir) {
  const entries = await fsPromises.readdir(draftsDir).catch(() => [])

  const halves = new Map() // uuid -> Set of extensions present ('md' | 'json')
  for (const name of entries) {
    if (name.endsWith('.tmp')) {
      // Orphaned from a killed process's atomic-write temp file -- never a
      // live pending write across a restart. Hygiene sweep, not required by
      // any locked criterion, but consistent with drafts/ design intent.
      await fsPromises.unlink(path.join(draftsDir, name)).catch(() => {})
      continue
    }
    const match = name.match(DRAFT_NAME_RE)
    if (!match) continue
    const [, uuid, ext] = match
    if (!halves.has(uuid)) halves.set(uuid, new Set())
    halves.get(uuid).add(ext)
  }

  const valid = []
  let corruptCount = 0

  for (const [uuid, exts] of halves) {
    if (!exts.has('md') || !exts.has('json')) {
      // Only one half present -- corrupt/partial, never throw.
      corruptCount++
      continue
    }

    try {
      const [content, rawJson] = await Promise.all([
        fsPromises.readFile(path.join(draftsDir, `${uuid}.md`), 'utf8'),
        fsPromises.readFile(path.join(draftsDir, `${uuid}.json`), 'utf8')
      ])
      const meta = JSON.parse(rawJson)
      valid.push({
        uuid,
        filePath: meta.filePath ?? null,
        name: meta.name,
        content,
        originalStat: meta.originalStat ?? null
      })
    } catch (err) {
      // Genuine failure (unparsable JSON, unreadable body) -- explicitly
      // handled as "skip and count" (PERS-02's own locked rule), never
      // silently swallowed. The caller only sees corruptCount, but the
      // error itself is never discarded from the log.
      console.error(`drafts-store: skipping corrupt draft "${uuid}":`, err)
      corruptCount++
    }
  }

  return { valid, corruptCount }
}

/**
 * Deletes every currently-valid draft pair in `draftsDir` (best-effort) --
 * the clean-quit backstop before-quit.js hooks into. A stray corrupt
 * half-pair is left untouched; sweep only ever touches uuids scanDraftsDir
 * reports as valid.
 */
async function sweepAllDrafts (draftsDir) {
  const { valid } = await scanDraftsDir(draftsDir)
  await Promise.all(valid.map(({ uuid }) => deleteDraft(draftsDir, uuid)))
}

/**
 * Registers the renderer-facing IPC surface for draft writes/deletes.
 * uuid generation defaults to main-process-only (crypto.randomUUID()), but
 * the renderer may propose its own already-known uuid to reuse on a repeat
 * write, and must supply one to delete (T-6-01 / Security Domain V12).
 *
 * [CR-02, 06-REVIEW.md] Both handlers re-validate any renderer-supplied
 * uuid against UUID_RE BEFORE it is ever used in a path.join() call, and
 * REJECT (throw) anything that does not match a canonical UUID shape --
 * never silently substitute a fresh id for a malformed one, which would
 * merely hide a bad caller rather than close the traversal gap. A
 * traversal-shaped uuid (e.g. '../../../../Users/Public/evil') is exactly
 * what this closes: main is this codebase's trust boundary, and main
 * re-validates renderer-supplied data even though the renderer is "our own"
 * code (path-guard.js's isSafeFilePath, before-quit.js's own 10-name cap
 * are the established precedent for this discipline).
 */
function registerDraftsIpc (draftsDir) {
  ipcMain.handle('draft:write', async (_event, uuid, content, meta) => {
    if (uuid != null && (typeof uuid !== 'string' || !UUID_RE.test(uuid))) {
      throw new Error('draft:write: uuid must be a canonical UUID string or omitted')
    }
    const id = uuid || crypto.randomUUID()
    await writeDraft(draftsDir, id, content, meta)
    return { uuid: id }
  })
  ipcMain.handle('draft:delete', async (_event, uuid) => {
    if (typeof uuid !== 'string' || !UUID_RE.test(uuid)) {
      throw new Error('draft:delete: uuid must be a canonical UUID string')
    }
    return deleteDraft(draftsDir, uuid)
  })
}

export {
  ensureDraftsDirExists,
  scanDraftsDir,
  writeDraft,
  deleteDraft,
  sweepAllDrafts,
  registerDraftsIpc
}
